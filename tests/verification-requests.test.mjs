import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../auth.js',import.meta.url),'utf8');
const fn=source.slice(source.indexOf('async function showVerification'),source.indexOf('async function start'));
let panel,sends=0,lookups=0,now=10000,fail=false;
const intervals=[],listeners={},storage=new Map();
const element=()=>({isConnected:true,children:[],setAttribute(){},append(...v){this.children.push(...v)},addEventListener(){},showModal(){},remove(){this.isConnected=false}});
const user={uid:'test',email:'test@example.com',emailVerified:false};
const document={hidden:false,body:{append(v){panel=v}},getElementById(){return panel},createElement:element,addEventListener(k,v){listeners[k]=v},removeEventListener(){}};
const localStorage={getItem:k=>storage.get(k),setItem:(k,v)=>storage.set(k,v)};
const context=vm.createContext({document,forms:[],message(){},localStorage,window:{localStorage,addEventListener(k,v){listeners[k]=v},removeEventListener(){}},navigator:{onLine:true},location:{},preferredLanguage:()=> 'en',Date:{now:()=>now},setInterval:fn=>intervals.push(fn),clearInterval(){},auth:{currentUser:user},api:{sendEmailVerification:async(...args)=>{sends++;assert.equal(args.length,1);if(fail)throw {code:'auth/too-many-requests'}},reload:async()=>{lookups++}},friendlyError:()=> 'error'});
vm.runInContext(fn,context);
await context.showVerification(user,true);
assert.equal(sends,1);
await panel.children[3].onclick();assert.equal(sends,1,'cooldown suppresses repeat send');
for(const tick of intervals)tick();assert.equal(lookups,0,'no periodic Firebase polling');
listeners.focus();await new Promise(setImmediate);assert.equal(lookups,1);
listeners.visibilitychange();await new Promise(setImmediate);assert.equal(lookups,1,'focus and visibility deduplicated');
now+=120001;fail=true;await panel.children[3].onclick();assert.equal(sends,2,'failed request is not retried automatically');
await context.showVerification(user,false);await panel.children[3].onclick();assert.equal(sends,2,'cooldown survives reopened dialog');
console.log('Verification: one send, no fallback retry, persisted cooldown, no background polling, deduplicated return checks.');
