import assert from 'node:assert/strict';
import {calculationEvent,summarizeCalculations} from '../analytics-data.js';
const selection=(crop,unit)=>({crop,unit,season:'Kharif',condition:'Irrigated'});
const a=calculationEvent('fertilizer',selection(' Rice ','acre'),2,{total:400});
assert.equal(a.areaHa,0.80937128448);
assert.equal(a.crop,'Rice');
const b=calculationEvent('seed',selection('rice','guntha'),40,{quantity:20});
const c=calculationEvent('yield',selection('Wheat','hectare'),2,{total:6000});
const summary=summarizeCalculations([{...a,uid:'a'},{...b,uid:'a'},{...c,uid:'b'}]);
assert.equal(summary.count,3); assert.equal(summary.active,2);
assert.equal(summary.crops[0].count,2);
assert.equal(summary.kinds.fertilizer.output,400);
assert.equal(summary.kinds.seed.output,20);
assert.equal(summary.kinds.yield.output/summary.kinds.yield.area,3000);
assert.ok(Math.abs(summary.averageArea-(a.areaHa+b.areaHa+c.areaHa)/3)<1e-12);
assert.equal(summarizeCalculations([]).averageArea,null);
assert.equal(summarizeCalculations([{kind:'bad',output:2,areaHa:2}]).count,0);
assert.throws(()=>calculationEvent('yield',selection('Rice','hectare'),0,{total:2}));
assert.throws(()=>calculationEvent('seed',selection('Rice','hectare'),1,{quantity:Infinity}));
console.log('Analytics: units, crop grouping, unique users, separate outputs and empty data verified.');
const {recordCalculation}=await import('../analytics.js');
globalThis.window={agriAuthenticated:true};
const browserStore=new Map();
globalThis.localStorage={getItem:key=>browserStore.get(key)??null,setItem:(key,value)=>browserStore.set(key,value)};
globalThis.document={getElementById:()=>({innerText:'Seed result'})};
const writes=[];
const api={collection:(_db,name)=>({path:name}),doc:collection=>({id:'event-1',path:`${collection.path}/event-1`}),serverTimestamp:()=> 'SERVER_TIME',setDoc:(ref,data)=>{writes.push({path:ref.path,data});return Promise.resolve();}};
recordCalculation({api,db:{},auth:{currentUser:{uid:'member'}}},'seed',selection('Rice','are'),100,{quantity:30});
assert.equal(writes.length,1);
assert.equal(writes[0].path,'calculationEvents/event-1');
assert.equal(writes[0].data.uid,'member');
assert.equal(writes[0].data.areaHa,1);
assert.equal(writes[0].data.season,'Kharif');
assert.equal(writes[0].data.condition,'Irrigated');
assert.equal(writes[0].data.unit,'are');
assert.equal(writes[0].data.createdAt,'SERVER_TIME');
const savedHistory=JSON.parse(browserStore.get('agro:member:history-v2'));
assert.equal(savedHistory.length,1);
assert.equal(savedHistory[0].crop,'Rice');
assert.equal(savedHistory[0].output,30);
assert.equal(savedHistory[0].resultText,'Seed result');
assert.equal(savedHistory[0].id,'event-1');
assert.ok(!browserStore.has('agro:someone-else:history-v2'));
window.agriAuthenticated=false;
recordCalculation({api,db:{},auth:{currentUser:{uid:'member'}}},'seed',selection('Rice','are'),100,{quantity:30});
assert.equal(writes.length,1);
delete globalThis.window;

delete globalThis.localStorage;
delete globalThis.document;
